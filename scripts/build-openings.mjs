// Rebuild a transposition-aware position book from CC0 Lichess opening lines.
import { writeFile } from 'node:fs/promises';
import { Chess } from '../web/vendor/chess.ts';
const positions = {}, named = {};
for (const letter of 'abcde') {
  const response = await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/master/${letter}.tsv`, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`Opening download failed: ${response.status}`);
  const [header, ...rows] = (await response.text()).trim().split(/\r?\n/);
  const columns = header.split('\t');
  for (const row of rows) {
    const values = row.split('\t');
    const name = values[columns.indexOf('name')], eco = values[columns.indexOf('eco')];
    const chess = new Chess();
    chess.loadPgn(values[columns.indexOf('pgn')]);
    const history = chess.history({ verbose: true });
    for (const move of history) {
      const key = move.after.split(' ').slice(0, 4).join(' ');
      positions[key] ||= [eco, name];
    }
    if (history.length) named[chess.fen().split(' ').slice(0, 4).join(' ')] ||= [eco, name];
  }
}
// An explicitly named position takes precedence over a longer line passing through it.
Object.assign(positions, named);
await writeFile(new URL('../web/vendor/openings.ts', import.meta.url), '// Lichess chess-openings (CC0), generated by scripts/build-openings.mjs.\nexport const OPENING_POSITIONS: Record<string, [string, string]> = ' + JSON.stringify(positions) + ';\n');
console.log(Object.keys(positions).length, 'opening positions');
